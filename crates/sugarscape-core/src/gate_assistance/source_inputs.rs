/// Explicit compiled dependency order for gate source receipts.
macro_rules! identity_bytes {
    ($p:expr) => {{
        #[cfg(not(target_arch = "wasm32"))]
        {
            include_bytes!($p).as_slice()
        }
        #[cfg(target_arch = "wasm32")]
        {
            b"".as_slice()
        }
    }};
}
